def z(v):
    return 0 if v is None else v


def seasons():
    """Emit Nov-Apr ski seasons assembled from adjacent cold-season rows."""
    out = []
    for y in sorted(ROWS):
        if y + 1 not in ROWS:
            continue
        nov, dec = ROWS[y][5], ROWS[y][6]
        if nov is None and dec is None:
            continue
        jan, feb, mar, apr = ROWS[y + 1][0:4]
        months = [z(nov), z(dec), z(jan), z(feb), z(mar), z(apr)]
        out.append({
            "season": f"{y}/{str(y + 1)[2:]}",
            "start_year": y,
            "nov": months[0], "dec": months[1], "jan": months[2],
            "feb": months[3], "mar": months[4], "apr": months[5],
            "total": sum(months),
            "jma_cold_year_total": ROWS[y + 1][7],
        })
    return out


